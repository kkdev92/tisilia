import { prefs, type Locale, type Theme } from "./prefs.js";

/** An input error as the Explorer collects it: the message, and a code that says what kind of error it is. */
export interface FieldErrorInfo {
  readonly message: string;
  /** "required", "body-required", "invalid-json", "no-request-input", "form-items", or a codec error code (`range`, `grammar` …). */
  readonly code?: string;
}

/** The message alone (`unknown enum member name`), for a field that already shows where: `code at /path: message` loses its prefix. */
export function shortError(error: { readonly message: string }): string {
  const at = error.message.indexOf(": ");
  return at >= 0 && /^[a-z-]+( at \S*)?$/.test(error.message.slice(0, at)) ? error.message.slice(at + 2) : error.message;
}

/** A number for display, grouped the way the chosen language writes it. */
export function formatNumber(n: number): string {
  return n.toLocaleString(prefs.locale === "ja" ? "ja-JP" : "en-US");
}

