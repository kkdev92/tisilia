        }
        function validateDecimal(value, path) {
          if (typeof value !== "object" || value === null || value.kind !== "decimal" || typeof value.coefficient !== "bigint" || value.coefficient < 0n || value.coefficient > decimalMax || !Number.isInteger(value.scale) || value.scale < 0 || value.scale > 28 || (value.sign !== 1 && value.sign !== -1)) {
            throw fail("type-mismatch", path, "Decimal value required");
          }
          return value;
        }
        function formatDecimal(d) {
          let digits = d.coefficient.toString();
          if (d.scale > 0) { digits = digits.padStart(d.scale + 1, "0"); digits = digits.slice(0, -d.scale) + "." + digits.slice(-d.scale); }
          return d.sign < 0 && d.coefficient !== 0n ? "-" + digits : digits;
        }
        const guidPattern = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
        function parseGuid(text, path) {
          if (!guidPattern.test(text)) throw fail("grammar", path, "guid must be in 8-4-4-4-12 hexadecimal form");
          return text.toLowerCase();
        }
        function validateGuid(value, path) {
          if (typeof value !== "string") throw fail("type-mismatch", path, "guid requires a string");
          return parseGuid(value, path);
        }
        // String.prototype.isWellFormed is ES2024 (Safari 16.4, Chrome 111, Firefox 119): the module runs in ES2022 browsers
        function isWellFormed(s) {
          for (let i = 0; i < s.length; i++) {
