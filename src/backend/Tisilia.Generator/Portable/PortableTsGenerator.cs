    private string Declarations()
    {
        var w = new CodeWriter();
        w.Line($"// Generated by Tisilia portable codec generator {Pipeline.GeneratorVersion}. Type declarations of the self-contained module.");
        w.Line("export interface PortableCodecContext { readonly path: string; }");
        w.Line("export type PortableJsonValue = { kind: \"null\" } | { kind: \"boolean\"; value: boolean } | { kind: \"string\"; value: string } | { kind: \"number\"; text: string } | { kind: \"array\"; items: readonly PortableJsonValue[] } | { kind: \"object\"; entries: readonly { name: string; value: PortableJsonValue }[] };");
        w.Line("export interface PortableDecimal { readonly kind: \"decimal\"; readonly sign: -1 | 1; readonly coefficient: bigint; readonly scale: number; }");
        w.Line("export interface PortableDateOnly { readonly kind: \"date-only\"; readonly year: number; readonly month: number; readonly day: number; }");
        w.Line("export interface PortableTimeOnly { readonly kind: \"time-only\"; readonly ticks: bigint; }");
        w.Line("export interface PortableDateTimeUtc { readonly kind: \"datetime-utc\"; readonly ticks: bigint; }");
        w.Line("export interface PortableDateTimeUnspecified { readonly kind: \"datetime-unspecified\"; readonly ticks: bigint; }");
        w.Line("export interface PortableDateTimeLocalWire { readonly kind: \"datetime-local-wire\"; readonly ticks: bigint; readonly offsetMinutes: number; }");
        w.Line("export interface PortableDateTimeOffset { readonly kind: \"datetime-offset\"; readonly ticks: bigint; readonly offsetMinutes: number; }");
        w.Line("export interface PortableDuration { readonly kind: \"duration\"; readonly ticks: bigint; }");
        foreach (var model in _project.Project.Models.OrderBy(m => m.Id, StringComparer.Ordinal))
        {
            if (model.Shape is ObjectShape shape)
            {
                var variant = PortableModel.VariantOf(_project, model.Id);
                var discriminator = variant is null ? null : PortableModel.DiscriminatorOf(_project, variant.Value.Union.Id);
                w.Open($"export interface {PortableModel.Pascal(model.TsName)} {{");
                foreach (var prop in shape.Properties)
                {
                    var type = prop.Name == discriminator ? PortableModel.Quote(variant!.Value.Tag) : TsType(prop.Use);
                    w.Line($"readonly {PortableModel.Quote(prop.Name)}{(prop.Presence == Presence.Optional ? "?" : "")}: {type};");
                }

                w.Close();
            }
            else if (model.Shape is UnionShape union)
            {
                w.Line($"export type {PortableModel.Pascal(model.TsName)} = {string.Join(" | ", union.Variants.Select(v => TsType(v.Use)))};");
            }
        }

        foreach (var def in _project.Definitions.OrderBy(d => d.Definition.Id, StringComparer.Ordinal))
        {
            var camel = Camel(def);
            var domain = TsType(new TypeUse { TypeId = (def.Definition.Request ?? def.Definition.Response)!.DomainTypeId, CodecId = "", SemanticNullable = false });
            w.Line($"export function {camel}DomainRule(value: unknown, context: PortableCodecContext): {domain};");
            w.Line($"export const {camel}Validate: {{ validateDomain(value: unknown, context: PortableCodecContext): {domain} }};");
            if (def.Definition.Response is not null)
            {
                w.Line($"export const {camel}ResponseDecode: {{ decodeResponse(wire: PortableJsonValue, context: PortableCodecContext): {domain} }};");
            }

            if (def.Definition.Request is not null)
            {
                w.Line($"export const {camel}RequestEncode: {{ encodeRequest(value: {domain}, context: PortableCodecContext): PortableJsonValue }};");
                w.Line($"export const {camel}RequestInput: {{ parseRequestInput(input: string | PortableJsonValue, context: PortableCodecContext): {domain} }};");
            }
        }

        return w.ToString();
    }

    private string TsType(TypeUse use)
    {
        string core;
        if (use.TypeId.StartsWith("std.", StringComparison.Ordinal))
        {
            core = PortableModel.TsScalarType(use.TypeId["std.".Length..]);
        }
        else if (_project.Models.TryGetValue(use.TypeId, out var model))
        {
            core = model.Shape switch
            {
                ArrayShape a => $"readonly ({TsType(a.Element)})[]",
                PrimitiveShape p => PortableModel.TsScalarType(PortableModel.ScalarName(p.PrimitiveId)),
                _ => PortableModel.Pascal(model.TsName),
            };
        }
        else
        {
            core = "unknown";
        }

        return use.SemanticNullable ? core + " | null" : core;
    }
