using Tisilia.Contract;
using Tisilia.Generator.Diagnostics;
using Tisilia.Generator.TypeScript;

namespace Tisilia.Generator.Portable;

/// <summary>
/// Emits the TypeScript side of a portable project as one self-contained ES module (no imports, so the Explorer can
/// load it as a raw browser artifact): per definition a domain rule/validator, the request encoder following the
/// canonical writer program, the response decoder following the response program, and a request-input factory that
/// accepts a lossless JSON AST. Every builtin scalar is parsed and written exactly by the module's own
/// prelude (<see cref="PortableTsPrelude"/>), tagged unions dispatch on their discriminator and nested objects follow their programs.
/// </summary>
public sealed class PortableTsGenerator
{
    private readonly LoadedPortableProject _project;
    private readonly DiagnosticBag _bag;
    private readonly List<string> _functions = [];
    private int _counter;

    /// <summary>The definition being emitted: nested models with a definition of their own are delegated to that definition's wire functions.</summary>
    private string? _currentDefinitionId;

    /// <summary>
    /// Which wire a decoder reads: "Response" (what the server writes) or "Request" (what the server reads — the Explorer's typed
    /// input). A nested definition is decoded with its program of the same direction: its request wire may accept what its
    /// response wire never writes (a number for a decimal written as a string).
    /// </summary>
    private string _decodeDirection = "Response";

    private PortableTsGenerator(LoadedPortableProject project, DiagnosticBag bag)
    {
        _project = project;
        _bag = bag;
    }

    public static IReadOnlyList<GeneratedFile> Generate(LoadedPortableProject project, DiagnosticBag bag)
    {
        var g = new PortableTsGenerator(project, bag);
        var baseName = project.Project.ProjectId + ".portable";
        return [new GeneratedFile(baseName + ".js", g.Module()), new GeneratedFile(baseName + ".d.ts", g.Declarations())];
    }

    private static string Camel(LoadedDefinition def) => PortableModel.Camel(def.Definition.Id.Split('.').Last());

    private string Module()
    {
        var w = new CodeWriter();
        w.Line($"// Generated by Tisilia portable codec generator {Pipeline.GeneratorVersion} for project {_project.Project.ProjectId}. Do not edit: owned by tisilia.portable-ownership.json.");
        w.Line("// Self-contained: no imports, so that the module can be served to browsers as a raw artifact.");
        w.Raw(Helpers);
        w.Raw(PortableTsPrelude.Scalars);
        foreach (var def in _project.Definitions.OrderBy(d => d.Definition.Id, StringComparer.Ordinal))
        {
            EmitDefinition(def);
        }

        foreach (var f in _functions)
        {
            w.Line();
            w.Raw(f);
        }

        return w.ToString();
    }

    private const string Helpers = """

        function fail(code, path, message) {
          const e = new Error(message);
          e.name = "CodecError";
          e.code = code;
          e.path = path;
          return e;
        }
        const decimalMax = 79228162514264337593543950335n;
        const integerRanges = {
          int8: [-128n, 127n], uint8: [0n, 255n], int16: [-32768n, 32767n], uint16: [0n, 65535n],
          int32: [-2147483648n, 2147483647n], uint32: [0n, 4294967295n],
          int64: [-9223372036854775808n, 9223372036854775807n], uint64: [0n, 18446744073709551615n],
        };
        function parseInteger(name, text, path) {
          if (!/^-?(?:0|[1-9][0-9]*)$/.test(text)) throw fail("grammar", path, name + " requires an integer lexeme");
          const v = BigInt(text);
          const [min, max] = integerRanges[name];
          if (v < min || v > max) throw fail("range", path, name + " out of range");
          return name === "int64" || name === "uint64" ? v : Number(v);
        }
        function validateInteger(name, value, path) {
          const big = name === "int64" || name === "uint64";
          let v;
          if (typeof value === "bigint") v = value;
          else if (typeof value === "number" && Number.isInteger(value)) v = BigInt(value);
          else throw fail("type-mismatch", path, name + " requires an integer");
          const [min, max] = integerRanges[name];
          if (v < min || v > max) throw fail("range", path, name + " out of range");
          return big ? v : Number(v);
        }
        function parseDecimal(text, path) {
          const m = /^(-?)(0|[1-9][0-9]*)(?:\.([0-9]+))?(?:[eE]([+-]?[0-9]+))?$/.exec(text);
          if (m === null) throw fail("grammar", path, "decimal requires a number lexeme");
          const frac = m[3] ?? "";
          let coefficient = BigInt(m[2] + frac);
          let scale = frac.length - (m[4] === undefined ? 0 : Number.parseInt(m[4], 10));
          while (scale < 0) { coefficient *= 10n; scale++; }
          while (scale > 28) {
            // System.Text.Json rounds beyond 28 fraction digits half away from zero
            const digit = coefficient % 10n; coefficient /= 10n; scale--;
            if (digit >= 5n && scale === 28) coefficient += 1n;
          }
          while (coefficient > decimalMax && scale > 0 && coefficient % 10n === 0n) { coefficient /= 10n; scale--; }
          if (coefficient > decimalMax) throw fail("range", path, "decimal out of the System.Decimal range");
