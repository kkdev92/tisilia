    private string EmitProject(string domainTypeId, List<string> methods, ref int counter)
    {
        var name = MethodName("Project", ref counter);
        var type = DomainTypeName(domainTypeId);
        var w = new CodeWriter();
        if (domainTypeId.StartsWith("std.", StringComparison.Ordinal) || (_project.Models.GetValueOrDefault(domainTypeId)?.Shape is PrimitiveShape))
        {
            var scalar = domainTypeId.StartsWith("std.", StringComparison.Ordinal) ? domainTypeId["std.".Length..] : PortableModel.ScalarName(((PrimitiveShape)_project.Models[domainTypeId].Shape).PrimitiveId);
            w.Line($"private static JsonValue {name}({type} value) => {ProjectScalarExpression(scalar, "value")};");
        }
        else if (_project.Models.TryGetValue(domainTypeId, out var model) && model.Shape is ObjectShape shape)
        {
            var variant = PortableModel.VariantOf(_project, domainTypeId);
            var discriminator = variant is null ? null : PortableModel.DiscriminatorOf(_project, variant.Value.Union.Id);
            w.Open($"private static JsonValue {name}({type} value) {{");
            w.Line("var entries = new System.Collections.Generic.List<JsonObjectEntry>();");
            foreach (var prop in shape.Properties)
            {
                if (prop.Name == discriminator)
                {
                    // the discriminator is projected first from the variant tag (unions carry the discriminator first)
                    w.Line($"entries.Add(new JsonObjectEntry {{ Name = {PortableModel.Quote(prop.Name)}, Value = DomainAst.String({PortableModel.Quote(variant!.Value.Tag)}) }});");
                    continue;
                }

                var access = "value." + PortableModel.CsIdentifier(prop.Name).TrimStart('@');
                var inner = EmitProjectUse(prop.Use, methods, ref counter);
                if (prop.Presence == Presence.Optional && !prop.Use.SemanticNullable)
                {
                    // a null non-nullable optional member is absent and omitted from the projected AST; nullable members project as null
                    w.Line($"if ({access} is not null) entries.Add(new JsonObjectEntry {{ Name = {PortableModel.Quote(prop.Name)}, Value = {inner}({access}{(IsValueType(prop.Use) ? ".Value" : "")}) }});");
                }
                else
                {
                    w.Line($"entries.Add(new JsonObjectEntry {{ Name = {PortableModel.Quote(prop.Name)}, Value = {inner}({access}) }});");
                }
            }

            w.Line("return new JsonObjectValue { Entries = entries };");
            w.Close();
        }
        else if (model?.Shape is ArrayShape array)
        {
            var element = EmitProjectUse(array.Element, methods, ref counter);
            w.Line($"private static JsonValue {name}(System.Collections.Generic.IReadOnlyList<{CsType(array.Element)}> value) => new JsonArrayValue {{ Items = value.Select(v => {element}(v)).ToList() }};");
        }
        else if (model?.Shape is UnionShape union)
        {
            w.Open($"private static JsonValue {name}({type} value) {{");
            w.Open("switch (value) {");
            var i = 0;
            foreach (var v in union.Variants)
            {
                var inner = EmitProjectUse(v.Use, methods, ref counter);
                w.Line($"case {DomainTypeName(v.Use.TypeId)} v{i}: return {inner}(v{i});");
                i++;
            }

            w.Line("default: throw new InvalidOperationException($\"value of type '{value.GetType().Name}' is not a declared variant\");");
            w.Close();
            w.Close();
        }
        else
        {
            w.Line($"private static JsonValue {name}({type} value) => throw new NotSupportedException();");
        }

        methods.Add(w.ToString());
        return name;
    }

    private string EmitProjectUse(TypeUse use, List<string> methods, ref int counter)
    {
        // models with a definition (declared or synthesized) project through that definition's converter; a self reference is a static call too
        var inner = _project.Models.TryGetValue(use.TypeId, out var m) && m.Shape is ObjectShape or UnionShape && PortableModel.DefinitionOfModel(_project, use.TypeId) is { } def
            ? ConverterName(def) + ".ProjectDomain"
            : EmitProject(use.TypeId, methods, ref counter);
        if (!use.SemanticNullable)
        {
            return inner;
        }

        var name = MethodName("ProjectNullable", ref counter);
        var type = CsType(use);
        var w = new CodeWriter();
        w.Line($"private static JsonValue {name}({type} value) => value is null ? new JsonNullValue() : {inner}(value{(IsValueType(use) ? ".Value" : "")});");
        methods.Add(w.ToString());
        return name;
    }

    private static string ProjectScalarExpression(string scalar, string v) => scalar switch
    {
        "string" => $"DomainAst.String({v})",
        "char" => $"DomainAst.String({v}.ToString())",
        "boolean" => $"DomainAst.Boolean({v})",
        "guid" => $"DomainAst.String(DomainAst.FormatGuid({v}))",
        "bytes" => $"DomainAst.String(Convert.ToBase64String({v}))",
        "json-value" => $"DomainAst.FromElement({v})",
        "int8" or "uint8" or "int16" or "uint16" or "int32" or "uint32" or "int64" or "uint64" => $"DomainAst.Number({v}.ToString(CultureInfo.InvariantCulture))",
        "decimal" => $"DomainAst.Number(DomainAst.FormatDecimal({v}))",
        "float32" => $"DomainAst.Float32({v})",
        "float64" => $"DomainAst.Float64({v})",
        _ => $"DomainAst.String(DomainAst.StjText({v}))",
    };

    private string EmitConstruct(string domainTypeId, List<string> methods, ref int counter)
    {
        var name = MethodName("Construct", ref counter);
        var type = DomainTypeName(domainTypeId);
        var w = new CodeWriter();
        if (domainTypeId.StartsWith("std.", StringComparison.Ordinal) || (_project.Models.GetValueOrDefault(domainTypeId)?.Shape is PrimitiveShape))
        {
            w.Line($"private static {type} {name}(JsonValue ast) => JsonSerializer.Deserialize<{type}>(DomainAst.ToJsonText(ast), global::Tisilia.TisiliaJson.Plain)!;");
        }
        else if (_project.Models.TryGetValue(domainTypeId, out var model) && model.Shape is ObjectShape shape)
        {
            var variant = PortableModel.VariantOf(_project, domainTypeId);
            var discriminator = variant is null ? null : PortableModel.DiscriminatorOf(_project, variant.Value.Union.Id);
            // the discriminator entry of a variant is dispatch information, not a record member
            var members = shape.Properties.Where(p => p.Name != discriminator).ToList();
            w.Open($"private static {type} {name}(JsonValue ast) {{");
            w.Line("if (ast is not JsonObjectValue obj) throw new FormatException(\"object AST required\");");
            foreach (var prop in members)
            {
                w.Line($"{CsType(prop.Use with { SemanticNullable = true })} v_{PortableModel.Camel(prop.Name)} = null;");
            }

            if (members.Count > 0)
            {
                w.Open("foreach (var entry in obj.Entries) {");
                w.Open("switch (entry.Name) {");
                foreach (var prop in members)
                {
                    var inner = EmitConstructUse(prop.Use, methods, ref counter);
                    w.Line($"case {PortableModel.Quote(prop.Name)}: v_{PortableModel.Camel(prop.Name)} = {inner}(entry.Value); break;");
                }

                w.Close();
                w.Close();
            }

            var args = members.Select(p =>
            {
                var v = "v_" + PortableModel.Camel(p.Name);
                var expr = p.Presence == Presence.Optional || p.Use.SemanticNullable ? v : v + " ?? throw new FormatException(\"missing " + p.Name + "\")";
                return $"{PortableModel.CsIdentifier(p.Name)}: {expr}";
            });
            w.Line($"return new {type}({string.Join(", ", args)});");
            w.Close();
        }
        else if (model?.Shape is ArrayShape array)
        {
            var element = EmitConstructUse(array.Element, methods, ref counter);
            w.Line($"private static System.Collections.Generic.IReadOnlyList<{CsType(array.Element)}> {name}(JsonValue ast) => ast is JsonArrayValue arr ? arr.Items.Select(i => {element}(i)).ToList() : throw new FormatException(\"array AST required\");");
        }
        else if (model?.Shape is UnionShape union)
        {
            var discriminator = PortableModel.DiscriminatorOf(_project, domainTypeId) ?? "kind";
            w.Open($"private static {type} {name}(JsonValue ast) {{");
            w.Line("if (ast is not JsonObjectValue obj) throw new FormatException(\"object AST required\");");
            w.Line($"var tag = DomainAst.Entry(obj, {PortableModel.Quote(discriminator)}) is JsonStringValue s ? s.Value : throw new FormatException(\"missing discriminator '{discriminator}'\");");
            w.Open("switch (tag) {");
            foreach (var v in union.Variants)
            {
                var inner = EmitConstructUse(v.Use, methods, ref counter);
                w.Line($"case {PortableModel.Quote(v.Tag)}: return {inner}(ast);");
            }

            w.Line("default: throw new FormatException($\"unknown discriminator '{tag}'\");");
            w.Close();
            w.Close();
        }
        else
        {
            w.Line($"private static {type} {name}(JsonValue ast) => throw new NotSupportedException();");
        }

        methods.Add(w.ToString());
        return name;
    }

    private string EmitConstructUse(TypeUse use, List<string> methods, ref int counter)
    {
        var inner = _project.Models.TryGetValue(use.TypeId, out var m) && m.Shape is ObjectShape or UnionShape && PortableModel.DefinitionOfModel(_project, use.TypeId) is { } def
            ? ConverterName(def) + ".ConstructDomain"
            : EmitConstruct(use.TypeId, methods, ref counter);
        if (!use.SemanticNullable)
        {
            return inner;
        }

        var name = MethodName("ConstructNullable", ref counter);
        var w = new CodeWriter();
        w.Line($"private static {CsType(use)} {name}(JsonValue ast) => ast is JsonNullValue ? null : {inner}(ast);");
        methods.Add(w.ToString());
        return name;
    }

