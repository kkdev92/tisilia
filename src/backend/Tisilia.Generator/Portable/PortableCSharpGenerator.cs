        w.Line("TypescriptOracleExport = \"\",");
        // wire ids follow the structural convention <typeId>.read / <typeId>.write so that nested models and refs resolve by name
        if (def.Request is { } request)
        {
            w.Line($"Request = new PairedDirection(Wire: f => {WireExpression(request.Program, modelId, WireDirection.ServerRead, modelId + ".read", def.Id)}, CodecExport: {PortableModel.Quote(camel + "RequestEncode")}, ValidateExport: {PortableModel.Quote(camel + "Validate")}, RequestInputExport: {PortableModel.Quote(camel + "RequestInput")}),");
        }

        if (def.Response is { } response)
        {
            w.Line($"Response = new PairedDirection(Wire: f => {WireExpression(response.Program, modelId, WireDirection.ServerWrite, modelId + ".write", def.Id)}, CodecExport: {PortableModel.Quote(camel + "ResponseDecode")}, ValidateExport: {PortableModel.Quote(camel + "Validate")}),");
        }

        w.Line("ConverterContext = [],");
        w.Line($"SettingsText = {PortableModel.Quote($"portable:{def.Id}@{def.DefinitionVersion}")},");
        w.Line($"Grade = Grade.{equivalence?.Grade.ToString() ?? "G2"},");
        w.Line($"Preserved = [{string.Join(", ", (equivalence?.Preserved ?? ["value"]).Select(PortableModel.Quote))}],");
        w.Line($"NotPreserved = [{string.Join(", ", (equivalence?.NotPreserved ?? []).Select(PortableModel.Quote))}],");
        w.Line($"Project = value => {converter}.ProjectDomain(({DomainTypeName(modelId)})value),");
        w.Line($"Construct = ast => {converter}.ConstructDomain(ast),");
        var dependencies = ReferencedDefinitions(def).Where(d => d.Definition.Id != def.Id).Select(d => $"typeof({d.Definition.ClrType})").Distinct(StringComparer.Ordinal).ToList();
        if (dependencies.Count > 0)
        {
            w.Line($"Dependencies = [{string.Join(", ", dependencies)}],");
        }

        w.Close("};");
    }

    /// <summary>Definitions a definition's programs depend on: refs, and the (declared or synthesized) definitions of nested object/union models.</summary>
    private IEnumerable<LoadedDefinition> ReferencedDefinitions(PortableDefinition def)
    {
        var found = new Dictionary<string, LoadedDefinition>(StringComparer.Ordinal);
        foreach (var direction in new[] { def.Request, def.Response })
        {
            if (direction is not null)
            {
                Collect(direction.Program, direction.DomainTypeId);
            }
        }

        return found.Values.Where(d => d.Definition.Id != def.Id).OrderBy(d => d.Definition.Id, StringComparer.Ordinal);

        void Collect(Program node, string domainTypeId)
        {
            switch (node)
            {
                case RefOp r:
                    if (PortableModel.Ref(_project, r.DefinitionId) is { } target)
                    {
                        found[target.Definition.Id] = target;
                    }

                    break;
                case NullableOp n:
                    Collect(n.Value, domainTypeId);
                    break;
                case ArrayOp a:
                    if (_project.Models.GetValueOrDefault(domainTypeId)?.Shape is ArrayShape array)
                    {
                        Collect(a.Element, array.Element.TypeId);
                    }

                    break;
                case ObjectOp o:
                {
                    if (PortableModel.DefinitionOfModel(_project, domainTypeId) is { } nested && nested.Definition.Id != def.Id)
                    {
                        found[nested.Definition.Id] = nested;
                    }

                    if (_project.Models.GetValueOrDefault(domainTypeId)?.Shape is ObjectShape shape)
                    {
                        foreach (var m in o.Members)
                        {
                            if (shape.Properties.FirstOrDefault(p => p.Name == m.Name) is { } prop)
                            {
                                Collect(m.Node, prop.Use.TypeId);
                            }
                        }
                    }

                    break;
                }

                case TokenUnionOp t:
                    foreach (var b in t.Branches)
                    {
                        Collect(b.Node, domainTypeId);
                    }

                    break;
                case TaggedUnionOp tg:
                {
                    if (PortableModel.DefinitionOfModel(_project, domainTypeId) is { } nested && nested.Definition.Id != def.Id)
                    {
                        found[nested.Definition.Id] = nested;
                    }

                    if (_project.Models.GetValueOrDefault(domainTypeId)?.Shape is UnionShape union)
                    {
                        foreach (var b in tg.Branches)
                        {
                            if (union.Variants.FirstOrDefault(v => v.Tag == b.Tag) is { } variant)
                            {
                                Collect(b.Node, variant.Use.TypeId);
                            }
                        }
                    }

                    break;
                }
            }
        }
    }

    private string ShapeExpression(string modelId)
    {
        if (!_project.Models.TryGetValue(modelId, out var model))
        {
            return $"new PrimitiveShape {{ PrimitiveId = Builtins.Scalar({PortableModel.Quote(modelId["std.".Length..])}) }}";
        }

        switch (model.Shape)
        {
            case ObjectShape shape:
            {
                var props = shape.Properties.Select(p => $"new DomainProperty {{ Name = {PortableModel.Quote(p.Name)}, Use = {UseExpression(p.Use)}, Presence = Presence.{p.Presence} }}");
                return $"new ObjectShape {{ Properties = [{string.Join(", ", props)}], Extension = new NoExtension() }}";
            }

            case ArrayShape array:
                return $"new ArrayShape {{ Element = {UseExpression(array.Element)} }}";
            case PrimitiveShape prim:
                return $"new PrimitiveShape {{ PrimitiveId = {PortableModel.Quote(prim.PrimitiveId)} }}";
            case UnionShape union:
            {
                var variants = union.Variants.Select(v => $"new UnionVariant {{ Tag = {PortableModel.Quote(v.Tag)}, Use = {UseExpression(v.Use)} }}");
                return $"new UnionShape {{ Variants = [{string.Join(", ", variants)}] }}";
            }

            default:
                return "throw new System.NotSupportedException(\"unsupported portable model shape\")";
        }
    }

    private string UseExpression(TypeUse use)
    {
        if (use.TypeId.StartsWith("std.", StringComparison.Ordinal))
        {
            var scalar = use.TypeId["std.".Length..];
            return use.SemanticNullable ? $"f.Builder.NullableScalar({PortableModel.Quote(scalar)})" : $"f.Builder.Scalar({PortableModel.Quote(scalar)})";
        }

        if (_project.Models.TryGetValue(use.TypeId, out var model))
        {
            if (model.Shape is ArrayShape array)
            {
                var inner = $"f.Builder.ArrayOf({PortableModel.Quote(model.Id)}, {PortableModel.Quote(model.TsName)}, {PortableModel.Quote(model.ClrIdentity)}, {UseExpression(array.Element)})";
                return use.SemanticNullable ? $"f.Builder.Nullable({inner})" : inner;
            }

            if (model.Shape is PrimitiveShape prim)
            {
                var scalar = PortableModel.ScalarName(prim.PrimitiveId);
                return use.SemanticNullable ? $"f.Builder.NullableScalar({PortableModel.Quote(scalar)})" : $"f.Builder.Scalar({PortableModel.Quote(scalar)})";
            }

        }

        // another portable definition (declared, or synthesized for a nested object/union model): its registration — a declared
        // dependency, so registered first — adds the model and codec <typeId>.codec with <typeId>.read/.write wires;
        // a nullable use wraps that codec's wires in a null branch
        var reference = $"new TypeUse {{ TypeId = {PortableModel.Quote(use.TypeId)}, CodecId = {PortableModel.Quote(use.TypeId + ".codec")}, SemanticNullable = false }}";
        return use.SemanticNullable ? $"f.Builder.Nullable({reference})" : reference;
    }

    /// <summary>A lambda body registering the wires of a program and returning the root wire ref.</summary>
    private string WireExpression(Program program, string domainTypeId, WireDirection direction, string rootId, string definitionId)
    {
        var statements = new List<string>();
        var root = EmitWire(program, domainTypeId, direction, rootId, statements, definitionId);
        return "{ " + string.Join(" ", statements) + " return " + root + "; }";
    }

    private string EmitWire(Program node, string domainTypeId, WireDirection direction, string id, List<string> statements, string definitionId)
    {
        var dir = direction == WireDirection.ServerRead ? "WireDirection.ServerRead" : "WireDirection.ServerWrite";
        switch (node)
        {
            case ScalarOp scalar:
            {
                var name = PortableModel.ScalarName(scalar.ScalarId);
                if (scalar.Representation == ScalarRepresentation.String)
                {
                    return $"f.StringWire({PortableModel.Quote(id)}, {dir}, Builtins.Grammar({PortableModel.Quote(name + "-string")}))";
                }

                return $"f.Scalar({PortableModel.Quote(name)}, {dir})";
            }

            case RefOp reference:
            {
                var target = PortableModel.Ref(_project, reference.DefinitionId);
                var targetModel = target?.Definition.Request?.DomainTypeId ?? target?.Definition.Response?.DomainTypeId ?? "unknown";
                var suffix = direction == WireDirection.ServerRead ? ".read" : ".write";
                return $"new WireRef {{ WireId = {PortableModel.Quote(targetModel + suffix)}, Direction = {dir} }}";
            }

            case NullableOp nullable:
            {
                var inner = EmitWire(nullable.Value, domainTypeId, direction, id + ".value", statements, definitionId);
                var nullId = direction == WireDirection.ServerRead ? "std.null.read" : "std.null.write";
                statements.Add($"f.Builder.AddWire(new Wire {{ Id = {PortableModel.Quote(nullId)}, Direction = {dir}, Shape = new NullWire() }});");
                statements.Add($"f.Builder.AddWire(new Wire {{ Id = {PortableModel.Quote(id)}, Direction = {dir}, Shape = new TokenUnionWire {{ Branches = [new TokenBranch {{ Token = JsonToken.Null, Wire = new WireRef {{ WireId = {PortableModel.Quote(nullId)}, Direction = {dir} }} }}, new TokenBranch {{ Token = JsonToken.{RootTokenName(nullable.Value)}, Wire = {inner} }}] }} }});");
                return $"new WireRef {{ WireId = {PortableModel.Quote(id)}, Direction = {dir} }}";
            }

            case ArrayOp array:
            {
                var elementType = _project.Models.TryGetValue(domainTypeId, out var m) && m.Shape is ArrayShape s ? s.Element.TypeId : domainTypeId;
                var element = EmitWire(array.Element, elementType, direction, id + ".element", statements, definitionId);
                statements.Add($"f.Builder.AddWire(new Wire {{ Id = {PortableModel.Quote(id)}, Direction = {dir}, Shape = new ArrayWire {{ Element = {element} }} }});");
                return $"new WireRef {{ WireId = {PortableModel.Quote(id)}, Direction = {dir} }}";
            }

            case ObjectOp obj:
            {
                var model = _project.Models.GetValueOrDefault(domainTypeId);
                var suffix = direction == WireDirection.ServerRead ? ".read" : ".write";
                if (model is not null && PortableModel.DefinitionOfModel(_project, domainTypeId) is { } nested && nested.Definition.Id != _currentDefinitionId)
                {
                    // the nested model's own registration declares its wire <modelId>.read/.write
                    return $"new WireRef {{ WireId = {PortableModel.Quote(domainTypeId + suffix)}, Direction = {dir} }}";
                }

                // an object model's wire is <modelId>.read/.write (the structural convention), so nested registrations and refs resolve it by name
                var wireId = model is null ? id : domainTypeId + suffix;
                var props = new List<string>();
                if (model is not null && PortableModel.VariantOf(_project, domainTypeId) is { } variant && PortableModel.DiscriminatorOf(_project, variant.Union.Id) is { } discriminator)
                {
                    // the variant's discriminator is a required literal wire of its tag, first in member order (SV13/SV50)
                    var litId = domainTypeId + ".tag" + suffix;
                    statements.Add($"f.Builder.AddWire(new Wire {{ Id = {PortableModel.Quote(litId)}, Direction = {dir}, Shape = new LiteralWire {{ Value = new JsonStringValue {{ Value = {PortableModel.Quote(variant.Tag)} }} }} }});");
                    props.Add($"new WireProperty {{ Name = {PortableModel.Quote(discriminator)}, Wire = new WireRef {{ WireId = {PortableModel.Quote(litId)}, Direction = {dir} }}, Presence = Presence.Required }}");
                }

                foreach (var member in obj.Members)
                {
                    var prop = (model?.Shape as ObjectShape)?.Properties.FirstOrDefault(p => p.Name == member.Name);
                    var memberWire = EmitWire(member.Node, prop?.Use.TypeId ?? domainTypeId, direction, wireId + ".members." + member.Name, statements, definitionId);
                    props.Add($"new WireProperty {{ Name = {PortableModel.Quote(member.Name)}, Wire = {memberWire}, Presence = Presence.{member.Presence} }}");
                }

                var additional = obj.UnknownMembers == UnknownMembers.Reject ? "new RejectAdditional()" : "new IgnoreAdditional()";
                statements.Add($"f.Builder.AddWire(new Wire {{ Id = {PortableModel.Quote(wireId)}, Direction = {dir}, Shape = new ObjectWire {{ Properties = [{string.Join(", ", props)}], Additional = {additional}, DuplicatePolicyId = Builtins.DuplicatesReject, NameMatchingId = Builtins.NamesOrdinal }} }});");
                return $"new WireRef {{ WireId = {PortableModel.Quote(wireId)}, Direction = {dir} }}";
            }

            case TaggedUnionOp tagged:
            {
                var union = _project.Models.GetValueOrDefault(domainTypeId)?.Shape as UnionShape;
                var unionSuffix = direction == WireDirection.ServerRead ? ".read" : ".write";
                if (union is not null && PortableModel.DefinitionOfModel(_project, domainTypeId) is { } nestedUnion && nestedUnion.Definition.Id != _currentDefinitionId)
                {
                    return $"new WireRef {{ WireId = {PortableModel.Quote(domainTypeId + unionSuffix)}, Direction = {dir} }}";
                }

                var wireId = union is null ? id : domainTypeId + unionSuffix;
                var variants = new List<string>();
                var i = 0;
                foreach (var branch in tagged.Branches)
                {
                    var variantType = union?.Variants.FirstOrDefault(v => v.Tag == branch.Tag)?.Use.TypeId ?? domainTypeId;
                    var wire = EmitWire(branch.Node, variantType, direction, wireId + ".branches." + i++, statements, definitionId);
                    variants.Add($"new TaggedVariant {{ Tag = new StringTag {{ Value = {PortableModel.Quote(branch.Tag)} }}, Wire = {wire} }}");
                }

                statements.Add($"f.Builder.AddWire(new Wire {{ Id = {PortableModel.Quote(wireId)}, Direction = {dir}, Shape = new TaggedUnionWire {{ Discriminator = {PortableModel.Quote(tagged.Discriminator)}, Variants = [{string.Join(", ", variants)}] }} }});");
                return $"new WireRef {{ WireId = {PortableModel.Quote(wireId)}, Direction = {dir} }}";
            }

            case TokenUnionOp union:
            {
                var branches = new List<string>();
                var i = 0;
                foreach (var branch in union.Branches)
                {
                    var wire = EmitWire(branch.Node, domainTypeId, direction, id + ".branches." + i++, statements, definitionId);
                    branches.Add($"new TokenBranch {{ Token = JsonToken.{branch.Token}, Wire = {wire} }}");
                }

                statements.Add($"f.Builder.AddWire(new Wire {{ Id = {PortableModel.Quote(id)}, Direction = {dir}, Shape = new TokenUnionWire {{ Branches = [{string.Join(", ", branches)}] }} }});");
                return $"new WireRef {{ WireId = {PortableModel.Quote(id)}, Direction = {dir} }}";
            }

            default:
                PortableModel.Unsupported(_bag, "/" + definitionId, $"unknown program op '{node.Op}'", definitionId);
                return $"new WireRef {{ WireId = {PortableModel.Quote(id)}, Direction = {dir} }}";
        }
    }

    private static string RootTokenName(Program program) => program switch
    {
        ScalarOp s when s.Representation == ScalarRepresentation.String => "String",
        ScalarOp s => PortableModel.ScalarName(s.ScalarId) switch
        {
            "boolean" => "Boolean",
            var n when Builtins.IsNumberTokenScalar(n) => "Number",
            _ => "String",
        },
        ObjectOp => "Object",
        ArrayOp => "Array",
        RefOp => "Object",
        _ => "Object",
    };
