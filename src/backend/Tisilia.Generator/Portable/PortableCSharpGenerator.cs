    private string RegistrationsFile()
    {
        var w = new CodeWriter();
        w.Raw(Header);
        w.Line("using Tisilia.AspNetCore.Bindings;");
        w.Line("using Tisilia.Contract;");
        w.Line("using Tisilia.Generator.Building;");
        w.Line("using Tisilia.Generator.Validation;");
        w.Line();
        w.Line($"namespace {_ns};");
        w.Line();
        w.Line($"/// <summary>Registrations of the portable module '{_project.Project.ProjectId}': TisiliaOptions.Codecs.AddPaired(...) for each.</summary>");
        w.Open($"public static class {PortableModel.Pascal(_project.Project.ProjectId)}Registrations {{");
        w.Line($"public const string ModuleId = {PortableModel.Quote(_project.Project.ProjectId)};");
        w.Line($"/// <summary>The generated TypeScript module, relative to the application's content root.</summary>");
        w.Line($"public const string TypescriptArtifact = {PortableModel.Quote(_tsArtifactPath)};");
        w.Line();
        w.Line("public static System.Collections.Generic.IReadOnlyList<PairedCodecRegistration> All(string contentRoot) =>");
        w.Line("[");
        foreach (var def in _project.Definitions.OrderBy(d => d.Definition.Id, StringComparer.Ordinal))
        {
            w.Line($"    {PortableModel.Pascal(def.Definition.Id.Split('.').Last())}(contentRoot),");
        }

        w.Line("];");
        w.Line();
        // the path is part of the contract and its semantic hash, so it must not depend on the host that loaded the assembly (dotnet run:
        // the project's bin/<configuration>/<tfm>/, a test host: its own output folder); conformance checks the artifact there (SV44)
        w.Line("// the project's own build output (bin/<configuration>/<tfm>/) whichever host loaded the assembly: the path is hashed into the contract");
        w.Open("private static string AssemblyArtifactPath(string contentRoot, System.Reflection.Assembly assembly) {");
        w.Line("var name = System.IO.Path.GetFileName(assembly.Location);");
        w.Line("var configuration = System.Reflection.CustomAttributeExtensions.GetCustomAttribute<System.Reflection.AssemblyConfigurationAttribute>(assembly)?.Configuration;");
        w.Line("var framework = System.Reflection.CustomAttributeExtensions.GetCustomAttribute<System.Runtime.Versioning.TargetFrameworkAttribute>(assembly)?.FrameworkName;");
        w.Open("if (configuration is not null && framework is not null) {");
        w.Line("var version = new System.Runtime.Versioning.FrameworkName(framework).Version;");
        w.Line("var output = $\"bin/{configuration}/net{version.Major}.{version.Minor}/{name}\";");
        w.Open("if (System.IO.File.Exists(System.IO.Path.Combine(contentRoot, output))) {");
        w.Line("return output;");
        w.Close();
        w.Close();
        w.Line("var relative = System.IO.Path.GetRelativePath(contentRoot, assembly.Location).Replace('\\\\', '/');");
        w.Line("return relative.StartsWith(\"..\", System.StringComparison.Ordinal) || System.IO.Path.IsPathRooted(relative) ? \"bin/\" + name : relative;");
        w.Close();
        foreach (var def in _project.Definitions.OrderBy(d => d.Definition.Id, StringComparer.Ordinal))
        {
            w.Line();
            EmitRegistration(w, def);
        }

        w.Close();
        return w.ToString();
    }

    private void EmitRegistration(CodeWriter w, LoadedDefinition loaded)
    {
        var def = loaded.Definition;
        _currentDefinitionId = def.Id;
        var converter = ConverterName(loaded);
        var modelId = def.Request?.DomainTypeId ?? def.Response!.DomainTypeId;
        var model = _project.Models.GetValueOrDefault(modelId);
        var equivalence = _project.Project.Equivalences.Concat(_project.SynthesizedEquivalences).FirstOrDefault(e => e.Id == (def.Response ?? def.Request)!.EquivalenceId);
        var shortName = PortableModel.Pascal(def.Id.Split('.').Last());
        var camel = PortableModel.Camel(def.Id.Split('.').Last());
        w.Open($"public static PairedCodecRegistration {shortName}(string contentRoot) => new() {{");
        w.Line($"ClrType = typeof({def.ClrType}),");
        w.Line($"ConverterType = typeof({converter}),");
        w.Line($"ModelId = {PortableModel.Quote(modelId)},");
        w.Line($"TsName = {PortableModel.Quote(model?.TsName ?? shortName)},");
        w.Line("Origin = CodecOrigin.Portable,");
        w.Line("BuiltinOracles = true,");
        w.Line($"Shape = f => {ShapeExpression(modelId)},");
        w.Line("ModuleId = ModuleId,");
        w.Line($"ModuleVersion = {PortableModel.Quote(def.DefinitionVersion)},");
